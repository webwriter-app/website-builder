import fs from "node:fs";
import path from "node:path";

const iconsDir = path.resolve(
  "node_modules/@shoelace-style/shoelace/dist/assets/icons"
);

const outFile = path.resolve("src/builder/data/shoelaceIcons.ts");

// Read *.svg filenames -> icon names
const names = fs
  .readdirSync(iconsDir)
  .filter((f) => f.endsWith(".svg"))
  .map((f) => f.slice(0, -4))
  .sort((a, b) => a.localeCompare(b));

const file = `/* AUTO-GENERATED FILE. DO NOT EDIT.
   Generated by scripts/generate-shoelace-icons.mjs */

export const SHOELACE_ICON_NAMES: string[] = ${JSON.stringify(names, null, 2)};

export const SHOELACE_ICON_OPTIONS: Array<{ label: string; value: string }> =
  SHOELACE_ICON_NAMES.map((name) => ({ label: name, value: name }));
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, file, "utf8");

console.log(
  `Wrote ${names.length} icons to ${path.relative(process.cwd(), outFile)}`
);